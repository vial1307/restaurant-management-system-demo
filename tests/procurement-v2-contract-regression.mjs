const supplier={closedWeekdays:[0],closedDates:["2026-10-12"],leadDays:1,reviewDays:2};
const calendar=[{date:"2026-10-10",type:"holiday"},{date:"2026-10-11",type:"holiday"},{date:"2026-10-12",type:"holiday"}];
const rule={enabled:true,supplierId:"configured-id",weekdayDemand:5,weekendDemand:8,holidayDemand:12,safetyStock:2,packageSize:10};
assert.equal(supplierClosed("2026-10-11",supplier),true);
assert.equal(supplierClosed("2026-10-12",supplier),true);
assert.equal(supplierClosed("2026-10-13",supplier),false);
assert.equal(nextReceiptDate("2026-10-10",supplier),"2026-10-13");
const plan=planProcurementLine({orderDate:"2026-10-10",supplier,calendar,stock:3,rule,incoming:[]});
assert.equal(plan.arrival,"2026-10-13");
assert.equal(plan.nextArrival,"2026-10-14");
assert.equal(plan.demand,41,"must sum three holiday days + following normal day");
assert.equal(plan.orderUnits,4,"40 units rounded to 4 packages of 10");
assert.equal(plan.preArrivalRisk,true,"flag unavoidable shortage before supplier resumes delivery");
assert.equal(planProcurementLine({orderDate:"2026-10-11",supplier,calendar,stock:0,rule,incoming:[]}).canOrder,false);
assert.equal(consumptionForDay("2026-10-11",rule,new Map([["2026-10-11","closed"]])),0,"restaurant closed day consumes zero");
assert.equal(consumptionForDay("2026-10-11",rule,new Map([["2026-10-11","holiday"]])),12);
const covered=planProcurementLine({orderDate:"2026-10-10",supplier,calendar,stock:15,rule,incoming:[{expectedArrival:"2026-10-12",baseQuantity:30,status:"confirmed"}]});
assert.equal(covered.orderUnits,0,"account for confirmed incoming deliveries before horizon end");
