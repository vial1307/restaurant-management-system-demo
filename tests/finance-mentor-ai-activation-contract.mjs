import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const wf=read(".github/workflows/finance-mentor-ai-activation.yml");
const runner=read("vps/finance/activate-mentor-ai.sh");
const deploy=read("vps/scripts/deploy-api.sh");
assert.match(wf,/^on:\n  workflow_dispatch:/m,"Activation only by manual dispatch");
assert.doesNotMatch(wf,/\n  push:|\n  schedule:|\n  pull_request:/,"No automatic key activation");
assert(wf.includes("secrets.FINANCE_OPENAI_API_KEY"),"Key must come from GitHub Actions secret");
assert(wf.includes("secrets.VPS_SSH_KEY"),"Use existing VPS deployment authentication");
assert(wf.includes('GITHUB_REF" == "refs/heads/main"'),"Only main branch may activate");
assert(wf.includes('LIVE" != "$EXPECTED"'),"Refuse activation on un-deployed code");
assert(wf.includes('FINANCE_OPENAI_API_KEY" |'),"Stream secret via SSH standard input");
assert(!wf.includes('echo "$FINANCE_OPENAI_API_KEY"'),"No stdout secret logging");
assert(!wf.includes("--key="),"Do not put secrets in SSH arguments");
assert.match(wf,/options:\n\s+- status\n\s+- activate\n\s+- disable/);
assert(wf.includes("FINANCE_AI_OWNER_AUTH_BOUNDARY_FAILED"),"Verify unauthenticated Mentor status stays private");
assert(runner.includes('MODE="${1:-}"'),"Bash mode input parsed normally");
assert(runner.includes('IFS= read -r key'),"Secret never passed in argv");
assert(runner.includes('APP_RELEASE="$(tr -d\x20\x27[:space:]\x27 < "$DIR/www/RELEASE")"'),"Manual API restart must preserve deployed APP_RELEASE");
assert(runner.includes("export APP_RELEASE"),"Restart must not report vps-dev as the production build");
assert(runner.includes("chmod 0600"),"Keep local private env files protected");
assert(runner.includes("awk '!/^(OPENAI_API_KEY|FINANCE_AI_ENABLED|FINANCE_AI_MODEL)=/'"),"Preserve all other env keys");
assert(runner.includes('trap rollback_and_clean EXIT'),"Rollback on error");
assert(runner.includes('FINANCE_AI_ROLLBACK_COMPLETED'),"Rollback is observable without exposing secrets");
assert(runner.includes('store:false'),"Do not store provider response");
assert(runner.includes('FINANCE_AI_PROVIDER_PROBE_OK'),"Test real provider connectivity");
assert(runner.includes('FINANCE_AI_DISABLED'),"Allow safe manual disable");
assert(!runner.includes('source "$ENV_FILE"'),"Do not execute .env as arbitrary code");
assert(!runner.includes("set -x\n"),"Must not trace secrets");
assert(!runner.includes('echo "$key"'),"Do not print confidential key");
assert(!runner.includes("docker compose down"),"Never shut down restaurant or finance DB");
assert(!runner.includes("migrate.sh"),"Never touch database schema");
assert(deploy.includes('install -o root -g root -m 0755 "$REPO_DIR/vps/finance/activate-mentor-ai.sh"'),"Deploy exact trusted runner");
assert(deploy.includes("deploy ALL=(root) NOPASSWD: /usr/local/sbin/kitchen-finance-ai-activate activate, /usr/local/sbin/kitchen-finance-ai-activate disable, /usr/local/sbin/kitchen-finance-ai-activate status"),"Sudoers allows only three commands");
console.log("PASS Finance Mentor AI opt-in activation security and rollback contract");
