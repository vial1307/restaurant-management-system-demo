export function currentLocale() {
  return document.documentElement.lang === "vi" ? "vi" : "zh-TW";
}

export function tr(key, options = {}) {
  const locale = options.locale || currentLocale();
  const zh = LOCALES["zh-TW"][key] || key;
  const vi = LOCALES.vi[key] || zh;
  if (locale === "vi") return options.bilingual === false ? vi : `${vi} · ${zh}`;
  return zh;
}
